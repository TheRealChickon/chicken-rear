"""Recreate the compiled pins and CTC dictionaries from the unmodified PaddleX tar files.

Usage: python prepare_catalog.py DIRECTORY_WITH_VENDOR_TARS (requires PyYAML).
Review the Git diff before adopting any upstream archive revision.
"""
import hashlib
import sys
import tarfile
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / "app/src/main/assets/circle-ocr"
SOURCE = ROOT / "app/src/main/java/dev/kb896/aiusage/circle/PaddleDistributions.kt"
PACKS = {
    "det": ("Text detector", "PP-OCRv5_mobile_det_onnx"),
    "latin": ("Latin", "latin_PP-OCRv5_mobile_rec_onnx"),
    "cjk": ("Chinese and Japanese", "PP-OCRv5_mobile_rec_onnx"),
    "korean": ("Korean", "korean_PP-OCRv5_mobile_rec_onnx"),
    "cyrillic": ("Cyrillic", "cyrillic_PP-OCRv5_mobile_rec_onnx"),
    "arabic": ("Arabic script", "arabic_PP-OCRv5_mobile_rec_onnx"),
    "devanagari": ("Devanagari", "devanagari_PP-OCRv5_mobile_rec_onnx"),
    "el": ("Greek", "el_PP-OCRv5_mobile_rec_onnx"),
    "th": ("Thai", "th_PP-OCRv5_mobile_rec_onnx"),
    "ta": ("Tamil", "ta_PP-OCRv5_mobile_rec_onnx"),
    "te": ("Telugu", "te_PP-OCRv5_mobile_rec_onnx"),
    "kannada": ("Kannada", "ka_PP-OCRv3_mobile_rec"),
    "eslav": ("East Slavic", "eslav_PP-OCRv5_mobile_rec_onnx"),
    "en": ("English", "en_PP-OCRv5_mobile_rec_onnx"),
    "det-accurate": ("Accurate text detector", "PP-OCRv5_server_det_onnx"),
    "cjk-accurate": ("Accurate Chinese and Japanese", "PP-OCRv5_server_rec_onnx"),
}


def main(folder):
    assets = []
    for key, (label, repository) in PACKS.items():
        path = folder / f"{repository}_infer.tar"
        with tarfile.open(path, "r:") as archive:
            files = {Path(m.name).name: m for m in archive if m.isfile()}
            model = files["inference.pdiparams" if key == "kannada" else "inference.onnx"]
            model_hash = hashlib.sha256(archive.extractfile(model).read()).hexdigest()
            tar_hash = hashlib.sha256(path.read_bytes()).hexdigest()
            assets.append(f'    OcrAsset("{key}", "{label}", "{path.name}",\n'
                          f'        {path.stat().st_size}, "{tar_hash}",\n'
                          f'        {model.offset_data}, {model.size}, "{model_hash}"),')
            if key not in ("det", "det-accurate"):
                config = yaml.safe_load(archive.extractfile(files["inference.yml"]))
                labels = config["PostProcess"]["character_dict"]
                assert all(isinstance(s, str) and "\n" not in s and "\r" not in s for s in labels)
                assert r"\s" not in labels
                encoded = [r"\s" if label == " " else label for label in labels]
                dictionary = "\n".join(encoded) + "\n"
                if key == "cjk-accurate":
                    assert dictionary == (ASSETS / "cjk.txt").read_text(encoding="utf-8"), "Server CTC dictionary changed"
                else:
                    (ASSETS / f"{key}.txt").write_text(dictionary, encoding="utf-8")
    SOURCE.write_text("package dev.kb896.aiusage.circle\n\n// Generated by scripts/ocr/prepare_catalog.py.\n"
                      "internal val paddleDistributions = listOf(\n" + "\n".join(assets) + "\n)\n")


if __name__ == "__main__":
    main(Path(sys.argv[1]))
